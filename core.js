const DIM_STATS = (() => {
  const mu = {}, sd = {};
  DIMS.forEach(d => {
    let m = 0, v = 0;
    QUESTIONS.forEach(q => {
      const ws = q.o.map(o => o[1][d] || 0);
      const mm = ws.reduce((a, b) => a + b, 0) / ws.length;
      m += mm;
      v += ws.reduce((a, b) => a + (b - mm) * (b - mm), 0) / ws.length;
    });
    mu[d] = m;
    sd[d] = Math.sqrt(v) || 1;
  });
  return { mu, sd };
})();
